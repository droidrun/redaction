"""Spec integrity (SPEC section 12): the embedded copy equals spec/, carries its hash, and a broken copy
makes the package refuse to import."""

import hashlib
import json
import shutil
import subprocess
import sys
import tomllib
from importlib import metadata, resources
from pathlib import Path

import droidrun_redaction
import pytest
from helpers import REPO_ROOT

HASHED_FILES = ["rules.json", "keys.json", "algorithms.json"]
PACKAGE_DIR = Path(droidrun_redaction.__file__).parent
EMBEDDED = resources.files("droidrun_redaction").joinpath("spec")


def spec_hash(read):
    digest = hashlib.sha256()
    for name in HASHED_FILES:
        digest.update(name.encode() + b"\0" + read(name) + b"\0")
    return digest.hexdigest()


def test_the_embedded_data_equals_the_spec_files():
    for name in HASHED_FILES:
        assert EMBEDDED.joinpath(name).read_bytes() == (REPO_ROOT / "spec" / name).read_bytes()
    for source in sorted((REPO_ROOT / "spec" / "vectors").iterdir()):
        assert EMBEDDED.joinpath("vectors", source.name).read_bytes() == source.read_bytes()


def test_the_generated_hash_is_the_hash_of_the_spec_files():
    expected = spec_hash(lambda name: (REPO_ROOT / "spec" / name).read_bytes())
    generated = (PACKAGE_DIR / "_spec_hash.py").read_text(encoding="utf-8")
    assert (
        generated
        == f'# Generated by tools/sync-spec.ts from spec/*.json: do not edit.\nSPEC_HASH = "{expected}"\n'
    )


def test_the_version_is_the_version_of_the_typescript_package():
    ts_version = json.loads((REPO_ROOT / "ts" / "package.json").read_text(encoding="utf-8"))["version"]
    project = tomllib.loads((REPO_ROOT / "python" / "pyproject.toml").read_text(encoding="utf-8"))
    assert project["project"]["version"] == ts_version
    assert metadata.version("droidrun-redaction") == ts_version


def import_copy(tmp_path, change):
    """Import a copy of the package in a fresh interpreter after `change(copy_dir)`; returns the process."""
    copy = tmp_path / "droidrun_redaction"
    shutil.copytree(PACKAGE_DIR, copy, ignore=shutil.ignore_patterns("__pycache__"))
    change(copy)
    return subprocess.run(
        [sys.executable, "-c", "import droidrun_redaction"],
        cwd=tmp_path,
        env={"PYTHONPATH": str(tmp_path), "PATH": ""},
        capture_output=True,
        text=True,
        timeout=60,
    )


def rewrite_spec(copy, name, change):
    """Change a data file of the copy and write the hash that matches it (so only the change fails)."""
    path = copy / "spec" / name
    data = json.loads(path.read_text(encoding="utf-8"))
    change(data)
    path.write_text(json.dumps(data), encoding="utf-8")
    new_hash = spec_hash(lambda file: (copy / "spec" / file).read_bytes())
    (copy / "_spec_hash.py").write_text(f'SPEC_HASH = "{new_hash}"\n', encoding="utf-8")


def test_an_unchanged_copy_imports(tmp_path):
    assert import_copy(tmp_path, lambda copy: None).returncode == 0


def test_a_changed_value_fails_the_hash_check(tmp_path):
    def change(copy):
        path = copy / "spec" / "rules.json"
        path.write_text(path.read_text(encoding="utf-8").replace("srt1", "srt9", 1), encoding="utf-8")

    process = import_copy(tmp_path, change)
    assert process.returncode != 0
    assert "SpecError: redaction spec does not match its hash" in process.stderr


def test_a_missing_data_file_fails(tmp_path):
    process = import_copy(tmp_path, lambda copy: (copy / "spec" / "keys.json").unlink())
    assert process.returncode != 0
    assert "SpecError: redaction spec data is missing" in process.stderr


def test_an_empty_rule_set_fails_even_with_a_matching_hash(tmp_path):
    process = import_copy(
        tmp_path, lambda copy: rewrite_spec(copy, "rules.json", lambda d: d.update(pipeline=[]))
    )
    assert process.returncode != 0
    assert "SpecError: redaction spec holds no rules" in process.stderr


def test_empty_secret_words_fail_even_with_a_matching_hash(tmp_path):
    process = import_copy(
        tmp_path, lambda copy: rewrite_spec(copy, "keys.json", lambda d: d.update(secretWords=[]))
    )
    assert process.returncode != 0
    assert "SpecError: redaction spec holds no rules" in process.stderr


@pytest.mark.parametrize("name", HASHED_FILES)
def test_an_unsupported_spec_version_fails(tmp_path, name):
    process = import_copy(tmp_path, lambda copy: rewrite_spec(copy, name, lambda d: d.update(specVersion=2)))
    assert process.returncode != 0
    assert "SpecError: unsupported redaction spec version" in process.stderr


def test_a_stale_hash_constant_fails(tmp_path):
    def change(copy):
        (copy / "_spec_hash.py").write_text('SPEC_HASH = "0"\n', encoding="utf-8")

    process = import_copy(tmp_path, change)
    assert process.returncode != 0
    assert "SpecError: redaction spec does not match its hash" in process.stderr


def test_an_empty_full_rule_list_fails_even_with_a_matching_hash(tmp_path):
    process = import_copy(
        tmp_path, lambda copy: rewrite_spec(copy, "rules.json", lambda d: d.update(full=[]))
    )
    assert process.returncode != 0
    assert "SpecError: redaction spec holds no rules" in process.stderr


def test_an_unknown_full_rule_kind_fails_at_import(tmp_path):
    def change(data):
        data["full"][0]["kind"] = "no-such-kind"

    process = import_copy(tmp_path, lambda copy: rewrite_spec(copy, "rules.json", change))
    assert process.returncode != 0
    assert "SpecError: redaction spec holds an unknown rule kind" in process.stderr


def test_an_unknown_check_fails_at_import_and_is_never_read_as_no_check(tmp_path):
    def change(data):
        rule = next(rule for rule in data["full"] if rule.get("check") == "base64-json")
        rule["check"] = "no-such-check"

    process = import_copy(tmp_path, lambda copy: rewrite_spec(copy, "rules.json", change))
    assert process.returncode != 0
    assert "SpecError: redaction spec names an unknown check" in process.stderr


def test_a_changed_letter_table_fails_the_hash_check(tmp_path):
    def change(copy):
        path = copy / "spec" / "algorithms.json"
        path.write_text(path.read_text(encoding="utf-8").replace('"41-5a,', '"41-59,', 1), encoding="utf-8")

    process = import_copy(tmp_path, change)
    assert process.returncode != 0
    assert "SpecError: redaction spec does not match its hash" in process.stderr
