#!/usr/bin/env bun
/**
 * sync-spec — generates what each language package embeds from `spec/`:
 *   - TypeScript: `ts/src/spec-data.generated.ts`, a module that holds the three data files as constants
 *     and their hash (no file access at runtime);
 *   - Python: a copy of the data files and `vectors/` inside the package, and `_spec_hash.py`, a module
 *     that holds the hash (the package compares it with its own data at import);
 *   - Go (when `go/` exists): a copy of the data files and `vectors/` under `go/spec`, and
 *     `go/spec_hash_gen.go`, the hash constant the package checks at start-up;
 *   - other languages (when their directory exists): a copy of the data files and `vectors/`.
 *
 *   bun tools/sync-spec.ts           write the generated files
 *   bun tools/sync-spec.ts --check   fail (exit 1) when a generated file is out of date
 *
 * The hash is SHA-256 over `name NUL bytes NUL` of rules.json, keys.json and
 * algorithms.json in that order (SPEC.md, "Spec integrity").
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '..');
const HASHED_FILES = ['rules.json', 'keys.json', 'algorithms.json'];
const SHIPPED_DIRS = ['vectors'];
const TS_MODULE = 'ts/src/spec-data.generated.ts';
const COPY_TARGETS = ['python/src/droidrun_redaction/spec', 'go/spec'];
const PYTHON_HASH_MODULE = 'python/src/droidrun_redaction/_spec_hash.py';
const GO_HASH_FILE = 'go/spec_hash_gen.go';

export function specHash(readFile: (name: string) => Buffer): string {
    const hash = createHash('sha256');
    for (const name of HASHED_FILES) {
        hash.update(`${name}\0`);
        hash.update(readFile(name));
        hash.update('\0');
    }
    return hash.digest('hex');
}

/** JSON text that is safe inside a TypeScript source file: every non-ASCII unit written as an escape. */
function asciiJson(bytes: Buffer): string {
    const text = JSON.stringify(JSON.parse(bytes.toString('utf8')), null, 2);
    return text.replace(
        /[\u007f-\uffff]/g,
        (unit) => `\\u${unit.charCodeAt(0).toString(16).padStart(4, '0')}`,
    );
}

/** The TypeScript module for the three data files (given as bytes by name). */
export function renderSpecModule(read: (name: string) => Buffer): string {
    const parts = HASHED_FILES.map((name) => {
        const constant = `${name.replace('.json', '').toUpperCase()}_DATA`;
        return `export const ${constant}: unknown = ${asciiJson(read(name))};\n`;
    });
    return [
        '// Generated by tools/sync-spec.ts from spec/*.json — do not edit.',
        `export const SPEC_HASH = '${specHash(read)}';`,
        '',
        ...parts,
    ].join('\n');
}

/** The Python module that holds the hash of the three data files. */
export function renderPythonHashModule(hash: string): string {
    return [
        '# Generated by tools/sync-spec.ts from spec/*.json: do not edit.',
        `SPEC_HASH = "${hash}"`,
        '',
    ].join('\n');
}

/** The Go source file that holds the hash of the embedded copy. */
export function renderGoHash(hash: string): string {
    return [
        '// Code generated by tools/sync-spec.ts from spec/*.json; DO NOT EDIT.',
        '',
        'package redaction',
        '',
        `const specHash = "${hash}"`,
        '',
    ].join('\n');
}

/** Every file a copy must hold: [relative path, bytes]. */
function sourceFiles(): Array<[string, Buffer]> {
    const files: Array<[string, Buffer]> = HASHED_FILES.map((name) => [
        name,
        readFileSync(join(ROOT, 'spec', name)),
    ]);
    for (const dir of SHIPPED_DIRS) {
        for (const name of readdirSync(join(ROOT, 'spec', dir)).sort()) {
            files.push([`${dir}/${name}`, readFileSync(join(ROOT, 'spec', dir, name))]);
        }
    }
    return files;
}

function listFiles(dir: string, prefix = ''): string[] {
    if (!existsSync(dir)) return [];
    return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
        const relative = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
        return entry.isDirectory() ? listFiles(join(dir, entry.name), relative) : [relative];
    });
}

function differs(path: string, bytes: Buffer | string): boolean {
    return !existsSync(path) || !readFileSync(path).equals(Buffer.from(bytes));
}

function write(path: string, bytes: Buffer | string): void {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, bytes);
}

function syncCopy(dir: string, files: Array<[string, Buffer]>, check: boolean): string[] {
    const targetDir = join(ROOT, dir);
    const stale: string[] = [];
    const wanted = new Set(files.map(([name]) => name));
    for (const [name, bytes] of files) {
        const path = join(targetDir, name);
        if (!differs(path, bytes)) continue;
        stale.push(join(dir, name));
        if (!check) write(path, bytes);
    }
    for (const extra of listFiles(targetDir).filter((name) => !wanted.has(name))) {
        stale.push(join(dir, extra));
    }
    return stale;
}

function main(): void {
    const check = process.argv.includes('--check');
    const files = sourceFiles();
    const byName = new Map(files);
    const read = (name: string): Buffer => byName.get(name) as Buffer;
    const stale: string[] = [];
    const rendered = renderSpecModule(read);
    if (differs(join(ROOT, TS_MODULE), rendered)) {
        stale.push(TS_MODULE);
        if (!check) write(join(ROOT, TS_MODULE), rendered);
    }
    const pythonHash = renderPythonHashModule(specHash(read));
    const pythonPackage = dirname(join(ROOT, PYTHON_HASH_MODULE));
    if (existsSync(pythonPackage) && differs(join(ROOT, PYTHON_HASH_MODULE), pythonHash)) {
        stale.push(PYTHON_HASH_MODULE);
        if (!check) write(join(ROOT, PYTHON_HASH_MODULE), pythonHash);
    }
    const goHash = renderGoHash(specHash(read));
    if (existsSync(join(ROOT, 'go')) && differs(join(ROOT, GO_HASH_FILE), goHash)) {
        stale.push(GO_HASH_FILE);
        if (!check) write(join(ROOT, GO_HASH_FILE), goHash);
    }
    for (const dir of COPY_TARGETS.filter((target) => existsSync(join(ROOT, target)))) {
        stale.push(...syncCopy(dir, files, check));
    }
    if (check && stale.length > 0) {
        console.error(`generated spec files are out of date; run tools/sync-spec:\n${stale.join('\n')}`);
        process.exit(1);
    }
    const hash = specHash(read);
    console.log(check ? `generated spec files are in sync (hash ${hash})` : `synced spec (hash ${hash})`);
}

if (import.meta.main) main();
