#!/usr/bin/env bun
/**
 * sync-spec — copies the data files of `spec/` into each language package and writes
 * the generated hash constant of the TypeScript package.
 *
 *   bun tools/sync-spec.ts           write the copies and the hash
 *   bun tools/sync-spec.ts --check   fail (exit 1) when a copy or the hash is out of date
 *
 * The hash is SHA-256 over `name NUL bytes NUL` of rules.json, keys.json and
 * algorithms.json in that order (SPEC.md, "Spec integrity").
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '..');
const HASHED_FILES = ['rules.json', 'keys.json', 'algorithms.json'];
const SHIPPED_DIRS = ['vectors'];
const TARGETS = [
    { dir: 'ts/spec', hashFile: 'ts/src/spec-hash.generated.ts', render: renderTsHash },
    { dir: 'python/src/droidrun_redaction/spec', hashFile: undefined, render: undefined },
    { dir: 'go/spec', hashFile: undefined, render: undefined },
];

export function specHash(readFile: (name: string) => Buffer): string {
    const hash = createHash('sha256');
    for (const name of HASHED_FILES) {
        hash.update(`${name}\0`);
        hash.update(readFile(name));
        hash.update('\0');
    }
    return hash.digest('hex');
}

function renderTsHash(hash: string): string {
    return `// Generated by tools/sync-spec.ts — do not edit.\nexport const SPEC_HASH = '${hash}';\n`;
}

/** Every file a copy must hold: [relative path, bytes]. */
function sourceFiles(): Array<[string, Buffer]> {
    const files: Array<[string, Buffer]> = HASHED_FILES.map((name) => [
        name,
        readFileSync(join(ROOT, 'spec', name)),
    ]);
    for (const dir of SHIPPED_DIRS) {
        for (const name of readdirSync(join(ROOT, 'spec', dir)).sort()) {
            files.push([`${dir}/${name}`, readFileSync(join(ROOT, 'spec', dir, name))]);
        }
    }
    return files;
}

function listFiles(dir: string, prefix = ''): string[] {
    if (!existsSync(dir)) return [];
    return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
        const relative = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
        return entry.isDirectory() ? listFiles(join(dir, entry.name), relative) : [relative];
    });
}

function differs(path: string, bytes: Buffer | string): boolean {
    return !existsSync(path) || !readFileSync(path).equals(Buffer.from(bytes));
}

function syncTarget(
    target: (typeof TARGETS)[number],
    files: Array<[string, Buffer]>,
    check: boolean,
): string[] {
    const targetDir = join(ROOT, target.dir);
    const stale: string[] = [];
    const wanted = new Set(files.map(([name]) => name));
    for (const [name, bytes] of files) {
        const path = join(targetDir, name);
        if (!differs(path, bytes)) continue;
        stale.push(join(target.dir, name));
        if (!check) {
            mkdirSync(dirname(path), { recursive: true });
            writeFileSync(path, bytes);
        }
    }
    for (const extra of listFiles(targetDir).filter((name) => !wanted.has(name)))
        stale.push(join(target.dir, extra));
    return stale;
}

function main(): void {
    const check = process.argv.includes('--check');
    const files = sourceFiles();
    const byName = new Map(files);
    const hash = specHash((name) => byName.get(name) as Buffer);
    const stale: string[] = [];
    for (const target of TARGETS) {
        const exists = existsSync(join(ROOT, target.dir)) || target.hashFile !== undefined;
        if (!exists) continue;
        stale.push(...syncTarget(target, files, check));
        if (target.hashFile === undefined || target.render === undefined) continue;
        const hashPath = join(ROOT, target.hashFile);
        const rendered = target.render(hash);
        if (differs(hashPath, rendered)) {
            stale.push(target.hashFile);
            if (!check) writeFileSync(hashPath, rendered);
        }
    }
    if (check && stale.length > 0) {
        console.error(`spec copies are out of date; run tools/sync-spec:\n${stale.join('\n')}`);
        process.exit(1);
    }
    console.log(check ? `spec copies are in sync (hash ${hash})` : `synced spec (hash ${hash})`);
}

if (import.meta.main) main();
